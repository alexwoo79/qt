#include <iostream> // 引入标准输入输出库，供 cout 和 endl 使用。
using namespace std; // 后续可直接写 cout，而不必写 std::cout。
 
int main()
{
   int a = 21; // 初始化操作数 a，后续多种复合赋值都会用到它。
   int c ; // 声明整数变量 c；赋值之前不要读取它。
 
   c =  a; // 普通赋值：把 a 的值 21 赋给 c。
   cout << "Line 1 - =  运算符实例，c 的值 = : " <<c<< endl ; // 输出：c = 21。
 
   c +=  a; // 等价于 c = c + a，即 21 + 21，c 变为 42。
   cout << "Line 2 - += 运算符实例，c 的值 = : " <<c<< endl ; // 输出：c = 42。
 
   c -=  a; // 等价于 c = c - a，即 42 - 21，c 变为 21。
   cout << "Line 3 - -= 运算符实例，c 的值 = : " <<c<< endl ; // 输出：c = 21。
 
   c *=  a; // 等价于 c = c * a，即 21 * 21，c 变为 441。
   cout << "Line 4 - *= 运算符实例，c 的值 = : " <<c<< endl ; // 输出：c = 441。
 
   c /=  a; // 等价于 c = c / a，即 441 / 21，c 变为 21。
   cout << "Line 5 - /= 运算符实例，c 的值 = : " <<c<< endl ; // 输出：c = 21。
 
   c  = 200; // 重新将 c 设为 200，为取余运算准备。
   c %=  a; // 等价于 c = c % a；200 除以 21 余 11，因此 c 变为 11。
   cout << "Line 6 - %= 运算符实例，c 的值 = : " <<c<< endl ; // 输出：c = 11。
 
   c <<=  2; // 左移 2 位，等价于非负整数乘以 2^2：11 * 4 = 44。
   cout << "Line 7 - <<= 运算符实例，c 的值 = : " <<c<< endl ; // 输出：c = 44。
 
   c >>=  2; // 右移 2 位；对当前正整数 44，相当于整除 4，结果为 11。
   cout << "Line 8 - >>= 运算符实例，c 的值 = : " <<c<< endl ; // 输出：c = 11。
 
   c &=  2; // 按位与：11(1011) & 2(0010) = 2(0010)，c 变为 2。
   cout << "Line 9 - &= 运算符实例，c 的值 = : " <<c<< endl ; // 输出：c = 2。
 
   c ^=  2; // 按位异或：2(0010) ^ 2(0010) = 0(0000)，相同位异或为 0。
   cout << "Line 10 - ^= 运算符实例，c 的值 = : " <<c<< endl ; // 输出：c = 0。
 
   c |=  2; // 按位或：0(0000) | 2(0010) = 2(0010)，任一位为 1 则结果为 1。
   cout << "Line 11 - |= 运算符实例，c 的值 = : " <<c<< endl ; // 输出：c = 2。
 
   return 0; // 返回 0，表示程序正常结束。
} // main 函数结束。